static size_t xp(const uint8_t **pp, char *out, size_t cap, size_t pos) {
	const uint8_t *p = *pp; uint8_t st[7]; unsigned sp = 0;
	for (;;) {
		uint8_t ch;
		if (sp) ch = st[--sp]; else { ch = *p++; if (!ch) break; }
		if (ch >= 0x80) { const uint8_t *t = &tok_tab[(ch - 0x80) * 2]; st[sp++] = t[1]; st[sp++] = t[0]; continue; }
		if (pos + 1 < cap) out[pos] = (char)ch;
		pos++;
	}
	*pp = p; return pos;
}
int lookup_symbol(uintptr_t addr, char *output_buffer, size_t capacity, uint32_t *offset_out) {
	if (capacity == 0 || output_buffer == NULL) return -1;
	if (addr < FIRST_ADDR) goto nf;
	uint32_t rel = (uint32_t)(addr - FIRST_ADDR);
	if ((rel >> 1) >= END_O) goto nf;
	const uint8_t *p; uint32_t kk, symrel, b, s;
	uint32_t o = rel >> 1, lo = 0, hi = NBLK;
	while (lo < hi) { uint32_t m = (lo + hi) >> 1; if (rdw(&dir_base[m * 3], 3) <= o) lo = m + 1; else hi = m; }
	b = lo - 1; uint32_t base = rdw(&dir_base[b * 3], 3);
	uint32_t am = rdw(&dir_am[b * 2], 2), ol = o - base, cnt, loc = 0;
	cnt = (b == NBLK - 1u) ? (NSYM - (NBLK - 1u) * BSZ) : BSZ;
	am >>= 0;
	unsigned ci = am & 1u; const uint8_t *sp_ = &addr_stream[am >> 1];
	unsigned kind, w; kk = 0;
	switch (ci) {
	case 0: kind = 0; w = 1; break;
	case 1: kind = 0; w = 2; break;
	default: kind = 0; w = 1; break;
	}
	{ uint32_t l = 0, h = cnt;
		while (h - l > 1) { uint32_t m = (l + h) >> 1; const uint8_t *q = &sp_[(m - 1) * w];
			uint32_t v = q[0]; if (w > 1) v |= (uint32_t)q[1] << 8;
			if (v <= ol) l = m; else h = m; }
		kk = l; if (l) { const uint8_t *q = &sp_[(l - 1) * w]; loc = q[0]; if (w > 1) loc |= (uint32_t)q[1] << 8; } }
	symrel = (base + loc) << 1; s = b * BSZ + kk;
	p = &name_pool[rdw(&dir_noff[b * 2], 2)];
	while (kk--) { while (*p++) { } }
	size_t full = xp(&p, output_buffer, capacity, 0);
	if (full + 1 <= capacity) output_buffer[full] = '\0'; else output_buffer[capacity - 1] = '\0';
	if (offset_out != NULL) *offset_out = rel - symrel;
	return (capacity >= full + 1) ? 0 : 2;
nf:
	if (offset_out) *offset_out = 0;
	if (capacity >= 2) { output_buffer[0] = '?'; output_buffer[1] = '\0'; } else { output_buffer[0] = '\0'; }
	return 1;
}

__attribute__((used, noinline))
void zephyr_fault_symbol_logger(uintptr_t fault_pc, char *log_buf, size_t buf_cap, uint32_t *offset_out) {
	lookup_symbol(fault_pc, log_buf, buf_cap, offset_out);
}
