static int cand_direct_decode_symbol(uint32_t sym_idx, char *buf, size_t buflen) {
	if (sym_idx >= CAND_DIRECT_NUM_SYMBOLS || buflen == 0) return -1;
	const uint8_t *p = &cand_direct_names_compressed[cand_direct_name_offsets[sym_idx]];
	size_t out = 0;
	while (*p != 0) {
		uint8_t byte = *p++;
		if (byte >= 0x80 && (byte - 0x80) < CAND_DIRECT_NUM_TOKENS) {
			uint32_t tok_idx = byte - 0x80;
			const char *tok = &cand_direct_dict_pool[cand_direct_dict_offsets[tok_idx]];
			while (*tok) { if (out + 1 < buflen) buf[out++] = *tok; tok++; }
		} else { if (out + 1 < buflen) buf[out++] = (char)byte; }
	}
	buf[out < buflen ? out : buflen - 1] = '\0';
	return (int)out;
}

int cand_direct_lookup(uintptr_t addr, char *output_buffer, size_t capacity, uint32_t *offset_out) {
	if (capacity == 0 || output_buffer == NULL) return -1;
	const uint32_t first_addr = CAND_DIRECT_FIRST_ADDR;
	uint32_t ret_offset = 0; int ret = 0;
	if (addr < first_addr) { if (offset_out) *offset_out = 0; output_buffer[0] = '?'; output_buffer[1] = '\0'; return 1; }
	const uint32_t symbol_offset = addr - first_addr;
	if (symbol_offset < cand_direct_addr_offsets[CAND_DIRECT_NUM_SYMBOLS - 1]) {
		uint32_t left = 0, right = CAND_DIRECT_NUM_SYMBOLS - 2;
		while (left <= right) {
			uint32_t mid = left + (right - left) / 2;
			if (symbol_offset >= cand_direct_addr_offsets[mid] && symbol_offset < cand_direct_addr_offsets[mid + 1]) {
				ret_offset = symbol_offset - cand_direct_addr_offsets[mid];
				ret = cand_direct_decode_symbol(mid, output_buffer, capacity);
				if (ret < 0) return -1;
				ret = 0; break;
			} else if (symbol_offset < cand_direct_addr_offsets[mid]) {
				if (mid == 0) break; right = mid - 1;
			} else { left = mid + 1; }
		}
	} else { output_buffer[0] = '?'; output_buffer[1] = '\0'; ret = 1; }
	if (offset_out != NULL) *offset_out = ret_offset;
	return ret;
}
int lookup_symbol(uintptr_t addr, char *output_buffer, size_t capacity, uint32_t *offset_out) {
	return cand_direct_lookup(addr, output_buffer, capacity, offset_out);
}

__attribute__((used, noinline))
void zephyr_fault_symbol_logger(uintptr_t fault_pc, char *log_buf, size_t buf_cap, uint32_t *offset_out) {
	lookup_symbol(fault_pc, log_buf, buf_cap, offset_out);
}
