/* Faithful Linux kallsyms decompressor */
static unsigned int kallsyms_m256_expand_symbol(unsigned int off, char *result, size_t maxlen) {
	if (maxlen == 0) return 0;
	const uint8_t *data = &kallsyms_m256_names[off];
	unsigned int len = *data++;
	size_t out = 0;
	while (len > 0) {
		uint8_t token_id = *data++;
		len--;
		const char *tptr = (const char *)&kallsyms_m256_token_table[kallsyms_m256_token_index[token_id]];
		while (*tptr != '\0') {
			if (out + 1 < maxlen) {
				result[out++] = *tptr;
			}
			tptr++;
		}
	}
	result[out < maxlen ? out : maxlen - 1] = '\0';
	return (unsigned int)out;
}

static unsigned int kallsyms_m256_get_symbol_offset(unsigned int pos) {
	unsigned int marker_idx = pos / KALLSYMS_MARKER_INTERVAL;
	unsigned int name_off = kallsyms_m256_markers[marker_idx];
	const uint8_t *name = &kallsyms_m256_names[name_off];
	unsigned int rem = pos % KALLSYMS_MARKER_INTERVAL;
	for (unsigned int i = 0; i < rem; i++) {
		name += (*name + 1);
	}
	return (unsigned int)(name - kallsyms_m256_names);
}

int kallsyms_m256_lookup(uintptr_t addr, char *buf, size_t buflen, uint32_t *offset) {
	if (buflen == 0) return -1;
	if (addr < KALLSYMS_FIRST_ADDR) {
		if (offset) *offset = 0;
		buf[0] = '?'; buf[1] = '\0';
		return 1; /* Not found */
	}
	uint32_t sym_offset = addr - KALLSYMS_FIRST_ADDR;
	if (sym_offset > kallsyms_m256_offsets[KALLSYMS_NUM_SYMS - 1] + 0x1000) {
		if (offset) *offset = 0;
		buf[0] = '?'; buf[1] = '\0';
		return 1;
	}
	/* Binary search */
	int left = 0, right = KALLSYMS_NUM_SYMS - 1;
	int match = -1;
	while (left <= right) {
		int mid = left + (right - left) / 2;
		if (kallsyms_m256_offsets[mid] <= sym_offset) {
			match = mid;
			left = mid + 1;
		} else {
			right = mid - 1;
		}
	}
	if (match < 0) {
		if (offset) *offset = 0;
		buf[0] = '?'; buf[1] = '\0';
		return 1;
	}
	if (offset) *offset = sym_offset - kallsyms_m256_offsets[match];
	unsigned int name_off = kallsyms_m256_get_symbol_offset((unsigned int)match);
	kallsyms_m256_expand_symbol(name_off, buf, buflen);
	return 0; /* Success */
}

int lookup_symbol(uintptr_t addr, char *output_buffer, size_t capacity, uint32_t *offset_out) {
	return kallsyms_m256_lookup(addr, output_buffer, capacity, offset_out);
}

__attribute__((used, noinline))
void zephyr_fault_symbol_logger(uintptr_t fault_pc, char *log_buf, size_t buf_cap, uint32_t *offset_out) {
	lookup_symbol(fault_pc, log_buf, buf_cap, offset_out);
}
