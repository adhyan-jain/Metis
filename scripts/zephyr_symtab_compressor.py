def learn_dictionary(names, budget):
    """
    Greedy Byte-Pair / Substring Token Learner:
    Learns up to `budget` tokens that maximize total string pool reduction.
    Token IDs: 0x80 .. 0x80 + budget - 1.
    """
    words = [[c for c in w] for w in names]
    dictionary = []
    
    for step in range(budget):
        cand_counts = collections.defaultdict(int)
        for w in words:
            n = len(w)
            i = 0
            while i < n:
                if isinstance(w[i], str):
                    j = i
                    while j < n and isinstance(w[j], str):
                        j += 1
                    s_run = "".join(w[i:j])
                    seen_in_run = set()
                    for l in range(2, min(len(s_run) + 1, 16)):
                        for k in range(len(s_run) - l + 1):
                            sub = s_run[k:k+l]
                            seen_in_run.add(sub)
                    for sub in seen_in_run:
                        cand_counts[sub] += 1
                    i = j
                else:
                    i += 1
                    
        best_cand = None
        best_save = 0
        for cand, count in cand_counts.items():
            save = count * (len(cand) - 1) - (len(cand) + 2)
            if save > best_save:
                best_save = save
                best_cand = cand
                
        if not best_cand or best_save <= 0:
            break
            
        token_id = 0x80 + len(dictionary)
        dictionary.append(best_cand)
        
        cand_len = len(best_cand)
        for w_idx in range(len(words)):
            w = words[w_idx]
            new_w = []
            idx = 0
            while idx < len(w):
                if all(idx + k < len(w) and w[idx+k] == best_cand[k] for k in range(cand_len)):
                    new_w.append(token_id)
                    idx += cand_len
                else:
                    new_w.append(w[idx])
                    idx += 1
            words[w_idx] = new_w

    return dictionary, words

def encode_names(names, dictionary):
    """Encodes list of names into list of bytearrays using dictionary."""
    encoded = []
    for name in names:
        w = [c for c in name]
        for token_idx, tok_str in enumerate(dictionary):
            token_id = 0x80 + token_idx
            cand_len = len(tok_str)
            new_w = []
            idx = 0
            while idx < len(w):
                if all(idx + k < len(w) and w[idx+k] == tok_str[k] for k in range(cand_len)):
                    new_w.append(token_id)
                    idx += cand_len
                else:
                    new_w.append(w[idx])
                    idx += 1
            w = new_w
        b = bytearray()
        for atom in w:
            if isinstance(atom, str):
                b.append(ord(atom))
            else:
                b.append(atom)
        b.append(0)
        encoded.append(bytes(b))
    return encoded

def measure_front_coding_diagnostic(entries):
    """Diagnostic measurement: front-coding in address order."""
    names = [e["name"] for e in entries]
    total_raw_bytes = sum(len(n) + 1 for n in names)
    front_coded_bytes = 0
    prev = ""
    for n in names:
        prefix_len = 0
        while prefix_len < len(prev) and prefix_len < len(n) and prev[prefix_len] == n[prefix_len]:
            prefix_len += 1
        suffix = n[prefix_len:]
        front_coded_bytes += 2 + len(suffix)
        prev = n
    return total_raw_bytes, front_coded_bytes

def generate_c_code(entries, dictionary, encoded_names, use_checkpoints=False, checkpoint_interval=16):
    first_addr = entries[0]["addr"]
    num_symbols = len(entries)
    
    dict_pool = bytearray()
    dict_offsets = []
    for tok in dictionary:
        dict_offsets.append(len(dict_pool))
        dict_pool.extend(tok.encode("ascii"))
        dict_pool.append(0)
        
    packed_names = bytearray()
    name_offsets = []
    for enc in encoded_names:
        name_offsets.append(len(packed_names))
        packed_names.extend(enc)

    checkpoints = []
    if use_checkpoints:
        for i in range(0, num_symbols, checkpoint_interval):
            checkpoints.append(name_offsets[i])

    code = []
    code.append("/* AUTO-GENERATED by zephyr_symtab_compressor.py - DO NOT EDIT */")
    code.append("#include <stdint.h>")
    code.append("#include <stddef.h>")
    code.append("#include <stdbool.h>")
    code.append("")
    code.append("#define Z_SYMTAB_NUM_SYMBOLS " + str(num_symbols))
    code.append("#define Z_SYMTAB_FIRST_ADDR  " + hex(first_addr))
    code.append("#define Z_SYMTAB_NUM_TOKENS   " + str(len(dictionary)))
    code.append("")
    
    code.append("static const uint32_t z_symtab_addr_offsets[" + str(num_symbols) + "] = {")
    for i, e in enumerate(entries):
        code.append(f"\t{hex(e['offset'])}, /* [{i}] {hex(e['addr'])} {e['name']} */")
    code.append("};")
    code.append("")

    if len(dictionary) > 0:
        code.append(f"static const char z_symtab_dict_pool[{len(dict_pool)}] = {{")
        chunks = [f"0x{b:02x}" for b in dict_pool]
        for i in range(0, len(chunks), 16):
            code.append("\t" + ", ".join(chunks[i:i+16]) + ",")
        code.append("};")
        code.append("")
        
        off_type = "uint8_t" if len(dict_pool) <= 256 else "uint16_t"
        code.append(f"static const {off_type} z_symtab_dict_offsets[{len(dict_offsets)}] = {{")
        for i, off in enumerate(dict_offsets):
            code.append(f"\t{off}, /* token 0x{0x80+i:02x}: {dictionary[i]!r} */")
        code.append("};")
        code.append("")

    if use_checkpoints:
        code.append(f"#define Z_SYMTAB_CHECKPOINT_INTERVAL {checkpoint_interval}")
        code.append(f"static const uint16_t z_symtab_checkpoints[{len(checkpoints)}] = {{")
        for cp in checkpoints:
            code.append(f"\t{cp},")
        code.append("};")
        code.append("")
    else:
        code.append(f"static const uint16_t z_symtab_name_offsets[{len(name_offsets)}] = {{")
        for noff in name_offsets:
            code.append(f"\t{noff},")
        code.append("};")
        code.append("")

    code.append(f"static const uint8_t z_symtab_names_compressed[{len(packed_names)}] = {{")
    chunks = [f"0x{b:02x}" for b in packed_names]
    for i in range(0, len(chunks), 16):
        code.append("\t" + ", ".join(chunks[i:i+16]) + ",")
    code.append("};")
    code.append("")

    code.append("/* Reentrant, zero-static-RAM symbol name decoder */")
    code.append("static int z_symtab_decode_symbol(uint32_t sym_idx, char *buf, size_t buflen) {")
    code.append("\tif (sym_idx >= Z_SYMTAB_NUM_SYMBOLS || buflen == 0) return -1;")
    code.append("")
    if use_checkpoints:
        code.append("\tuint32_t cp_idx = sym_idx / Z_SYMTAB_CHECKPOINT_INTERVAL;")
        code.append("\tuint32_t rem = sym_idx % Z_SYMTAB_CHECKPOINT_INTERVAL;")
        code.append("\tconst uint8_t *p = &z_symtab_names_compressed[z_symtab_checkpoints[cp_idx]];")
        code.append("\twhile (rem > 0) {")
        code.append("\t\twhile (*p++ != 0) { }")
        code.append("\t\trem--;")
        code.append("\t}")
    else:
        code.append("\tconst uint8_t *p = &z_symtab_names_compressed[z_symtab_name_offsets[sym_idx]];")
    code.append("")
    code.append("\tsize_t out = 0;")
    code.append("\twhile (*p != 0) {")
    code.append("\t\tuint8_t byte = *p++;")
    if len(dictionary) > 0:
        code.append("\t\tif (byte >= 0x80 && (byte - 0x80) < Z_SYMTAB_NUM_TOKENS) {")
        code.append("\t\t\tuint32_t tok_idx = byte - 0x80;")
        code.append("\t\t\tconst char *tok = &z_symtab_dict_pool[z_symtab_dict_offsets[tok_idx]];")
        code.append("\t\t\twhile (*tok) {")
        code.append("\t\t\t\tif (out + 1 < buflen) { buf[out++] = *tok; }")
        code.append("\t\t\t\ttok++;")
        code.append("\t\t\t}")
        code.append("\t\t} else {")
        code.append("\t\t\tif (out + 1 < buflen) { buf[out++] = (char)byte; }")
        code.append("\t\t}")
    else:
        code.append("\t\tif (out + 1 < buflen) { buf[out++] = (char)byte; }")
    code.append("\t}")
    code.append("\tbuf[out < buflen ? out : buflen - 1] = '\\0';")
    code.append("\treturn (int)out;")
    code.append("}")
    code.append("")

    code.append("/* Address to symbol name resolution with caller-provided buffer */")
    code.append("int symtab_find_symbol_name_r(uintptr_t addr, uint32_t *offset, char *buf, size_t buflen) {")
    code.append("\tif (buflen == 0) return -1;")
    code.append("\tconst uint32_t first_addr = Z_SYMTAB_FIRST_ADDR;")
    code.append("\tuint32_t ret_offset = 0;")
    code.append("\tint ret = 0;")
    code.append("")
    code.append("\tif (addr < first_addr) {")
    code.append("\t\tif (offset) *offset = 0;")
    code.append("\t\tbuf[0] = '?'; buf[1] = '\\0';")
    code.append("\t\treturn 1;")
    code.append("\t}")
    code.append("")
    code.append("\tconst uint32_t symbol_offset = addr - first_addr;")
    code.append("\tif (symbol_offset < z_symtab_addr_offsets[Z_SYMTAB_NUM_SYMBOLS - 1]) {")
    code.append("\t\tuint32_t left = 0;")
    code.append("\t\tuint32_t right = Z_SYMTAB_NUM_SYMBOLS - 2;")
    code.append("\t\twhile (left <= right) {")
    code.append("\t\t\tuint32_t mid = left + (right - left) / 2;")
    code.append("\t\t\tif (symbol_offset >= z_symtab_addr_offsets[mid] &&")
    code.append("\t\t\t    symbol_offset < z_symtab_addr_offsets[mid + 1]) {")
    code.append("\t\t\t\tret_offset = symbol_offset - z_symtab_addr_offsets[mid];")
    code.append("\t\t\t\tret = z_symtab_decode_symbol(mid, buf, buflen);")
    code.append("\t\t\t\tbreak;")
    code.append("\t\t\t} else if (symbol_offset < z_symtab_addr_offsets[mid]) {")
    code.append("\t\t\t\tif (mid == 0) break;")
    code.append("\t\t\t\tright = mid - 1;")
    code.append("\t\t\t} else {")
    code.append("\t\t\t\tleft = mid + 1;")
    code.append("\t\t\t}")
    code.append("\t\t}")
    code.append("\t} else {")
    code.append("\t\tbuf[0] = '?'; buf[1] = '\\0';")
    code.append("\t\tret = 1;")
    code.append("\t}")
    code.append("")
    code.append("\tif (offset != NULL) { *offset = ret_offset; }")
    code.append("\treturn ret;")
    code.append("}")
    code.append("")

    return "\n".join(code), {
        "num_symbols": num_symbols,
        "num_tokens": len(dictionary),
        "addr_offsets_bytes": num_symbols * 4,
        "dict_pool_bytes": len(dict_pool),
        "dict_offsets_bytes": len(dict_offsets) * (1 if len(dict_pool) <= 256 else 2),
        "name_offsets_bytes": len(checkpoints) * 2 if use_checkpoints else len(name_offsets) * 2,
        "compressed_names_bytes": len(packed_names),
        "total_rodata_bytes": (num_symbols * 4) + len(dict_pool) + (len(dict_offsets) * (1 if len(dict_pool) <= 256 else 2)) + (len(checkpoints) * 2 if use_checkpoints else len(name_offsets) * 2) + len(packed_names)
    }

